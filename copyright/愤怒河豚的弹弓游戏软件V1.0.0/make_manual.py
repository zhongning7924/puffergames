    for _ in range(6):
        doc.add_paragraph()
    cp = doc.add_paragraph(); cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_font(cp.add_run('%s\n%s\n操 作 手 册' % (NAME, VER)), '黑体', 26, bold=True)
    doc.add_page_break()

    first_h1 = True
    for item in C:
        t = item[0]
        if t == 'h1':
            if not first_h1:
                doc.add_page_break()
            first_h1 = False
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(14)
            p.paragraph_format.space_after = Pt(8)
            set_font(p.add_run(item[1]), '黑体', 16, bold=True)
        elif t == 'h2':
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(10)
            p.paragraph_format.space_after = Pt(6)
            set_font(p.add_run(item[1]), '黑体', 13, bold=True)
        elif t == 'p':
            p = doc.add_paragraph()
            pf = p.paragraph_format
            pf.first_line_indent = Pt(24)
            pf.line_spacing = 1.5
            set_font(p.add_run(item[1]), '宋体', 12)
        elif t == 'table':
            headers, rows = item[1], item[2]
            ncol = len(headers)
            tbl = doc.add_table(rows=len(rows) + 1, cols=ncol)
            tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
            tbl.autofit = False
            set_borders(tbl)
            total_w = 17.0
            first_w = 3.2 if ncol <= 4 else 2.6
            rest_w = (total_w - first_w) / (ncol - 1) if ncol > 1 else total_w
            widths = [first_w] + [rest_w] * (ncol - 1)
            for j, htxt in enumerate(headers):
                cell = tbl.rows[0].cells[j]
                cell.width = Cm(widths[j])
                cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
                set_font(cell.paragraphs[0].add_run(htxt), '黑体', 10.5, bold=True)
                shd = OxmlElement('w:shd')
                shd.set(qn('w:val'), 'clear'); shd.set(qn('w:fill'), 'EEEEEE')
                cell._tc.get_or_add_tcPr().append(shd)
            # 表头跨页重复 + 行不跨页断开
            trPr = tbl.rows[0]._tr.get_or_add_trPr()
            th = OxmlElement('w:tblHeader'); th.set(qn('w:val'), 'true'); trPr.append(th)
            for row in tbl.rows:
                rp = row._tr.get_or_add_trPr()
                cs = OxmlElement('w:cantSplit'); cs.set(qn('w:val'), 'true'); rp.append(cs)
            for i, row in enumerate(rows):
                for j, val in enumerate(row):
                    cell = tbl.rows[i + 1].cells[j]
                    cell.width = Cm(widths[j])
                    set_font(cell.paragraphs[0].add_run(str(val)), '宋体', 10.5)
        elif t == 'img':
            width = item[3] if len(item) > 3 else 7.2
            p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.add_run().add_picture(os.path.join(OUT, item[1]), width=Cm(width))
        elif t == 'caption':
            p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            set_font(p.add_run(item[1]), '宋体', 10.5)

    p = os.path.join(OUT, '操作手册.docx')
    doc.save(p)
    return p


